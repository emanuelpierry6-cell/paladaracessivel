-- Paladar Acessível | Banco de dados de indicações
-- Execute este arquivo no Supabase > SQL Editor > New query.

create table if not exists public.sugestoes (
  id bigint generated by default as identity primary key,
  restaurante text not null check (char_length(trim(restaurante)) between 2 and 120),
  endereco text not null check (char_length(trim(endereco)) between 5 and 240),
  bairro text not null check (char_length(trim(bairro)) between 2 and 80),
  categoria text,
  recursos_acessibilidade text not null check (char_length(trim(recursos_acessibilidade)) between 3 and 2000),
  email_sugerente text,
  status text not null default 'pendente' check (status in ('pendente','em_analise','aprovada','rejeitada')),
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now()
);

create index if not exists sugestoes_status_idx on public.sugestoes(status);
create index if not exists sugestoes_criado_em_idx on public.sugestoes(criado_em desc);

alter table public.sugestoes enable row level security;

-- Permissões de tabela: envio público; leitura e gestão apenas autenticadas.
grant insert on table public.sugestoes to anon, authenticated;
grant select, update on table public.sugestoes to authenticated;
grant usage, select on sequence public.sugestoes_id_seq to anon, authenticated;

-- Visitantes podem enviar indicações, mas não podem consultar nem alterar registros.
drop policy if exists "Visitantes podem enviar sugestoes" on public.sugestoes;
create policy "Visitantes podem enviar sugestoes"
  on public.sugestoes for insert to anon, authenticated
  with check (status = 'pendente');

-- Somente usuários autenticados podem consultar e administrar sugestões.
drop policy if exists "Equipe autenticada pode consultar sugestoes" on public.sugestoes;
create policy "Equipe autenticada pode consultar sugestoes"
  on public.sugestoes for select to authenticated
  using (true);

drop policy if exists "Equipe autenticada pode atualizar sugestoes" on public.sugestoes;
create policy "Equipe autenticada pode atualizar sugestoes"
  on public.sugestoes for update to authenticated
  using (true) with check (true);

